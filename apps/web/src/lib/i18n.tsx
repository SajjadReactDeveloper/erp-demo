export const STR_AR = AR;

interface Ctx { lang: Lang; dir: 'rtl' | 'ltr'; t: (k: string, vars?: Record<string, string | number>) => string; setLang: (l: Lang) => void; fl: (r: ResourceDef, f: Field | string) => string; rl: (r: ResourceDef | string, plural?: boolean) => string; el: (v: string) => string }
const C = createContext<Ctx | null>(null);

export function LocaleProvider({ initial, children }: { initial: Lang; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  const setLang = useCallback((l: Lang) => { document.cookie = `locale=${l}; path=/; max-age=31536000; samesite=lax`; setLangState(l); document.documentElement.lang = l; document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr'; }, []);
  useEffect(() => { document.documentElement.lang = lang; document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'; }, [lang]);
  const value = useMemo<Ctx>(() => ({
    lang, dir: lang === 'ar' ? 'rtl' : 'ltr', setLang,
    t: (k, vars) => { let s = lang === 'ar' ? AR[k] ?? k : k; if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b)); return s; },
    fl: (_r, f) => { const n = typeof f === 'string' ? f : f.name; return lang === 'ar' ? labelAr(n) : labelEn(n); },
    rl: (r, plural) => { const x = typeof r === 'string' ? BY_KEY[r] : r; if (!x) return String(r); return lang === 'ar' ? (plural ? x.arPlural : x.ar) : plural ? x.enPlural : x.en; },
    el: (v) => enumLbl(v, lang),
  }), [lang, setLang]);
  return <C.Provider value={value}>{children}</C.Provider>;
}
export const useT = () => { const c = useContext(C); if (!c) throw new Error('LocaleProvider missing'); return c; };
