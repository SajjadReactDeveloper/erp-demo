import { writeFileSync } from 'node:fs';
import { RESOURCES, BY_KEY, validateRegistry, Field, ResourceDef } from '@erp/shared';

const errs = validateRegistry();
if (errs.length) {
  console.error('Registry errors:\n' + errs.join('\n'));
  process.exit(1);
}

const snake = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const relName = (f: Field) => (f.name.endsWith('Id') ? f.name.slice(0, -2) : f.name + 'Rel');

// which (child, fk) pairs cascade when parent is deleted
const cascade = new Set<string>();
for (const r of RESOURCES) for (const c of r.children) cascade.add(`${c.key}.${c.fk}`);

const scalar = (r: ResourceDef, f: Field): string[] => {
  const nonNull = f.required && !f.readonly;
  const q = nonNull ? '' : '?';
  switch (f.type) {
    case 'string': return [`${f.name} String${q}`];
    case 'text': return [`${f.name} String${q} @db.Text`];
    case 'int': return [f.required ? `${f.name} Int` : f.readonly ? `${f.name} Int @default(0)` : `${f.name} Int?`];
    case 'decimal': return [f.required ? `${f.name} Decimal @db.Decimal(18,4)` : f.readonly ? `${f.name} Decimal @default(0) @db.Decimal(18,4)` : `${f.name} Decimal? @db.Decimal(18,4)`];
    case 'bool': return [`${f.name} Boolean @default(${f.name === 'isActive' ? 'true' : 'false'})`];
    case 'date': return [`${f.name} DateTime${q} @db.Date`];
    case 'datetime': return [`${f.name} DateTime${q}`];
    case 'json': return [`${f.name} Json?`];
    case 'enum': return [`${f.name} String @default("${f.values![0]}")`];
    case 'ref': {
      const t = BY_KEY[f.ref!];
      const rel = `rel_${r.key}_${f.name}`;
      const onDel = cascade.has(`${r.key}.${f.name}`) ? ', onDelete: Cascade' : '';
      return [`${f.name} String${q}`, `${relName(f)} ${t.key}${q} @relation("${rel}", fields: [${f.name}], references: [id]${onDel})`];
    }
  }
};

const lines: string[] = [];
lines.push(`// AUTO-GENERATED by scripts/gen-schema.ts from @erp/shared registry. Do not edit by hand.`);
lines.push(`generator client {\n  provider = "prisma-client-js"\n}\n`);
lines.push(`datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}\n`);

// back-relations per target
const back: Record<string, string[]> = {};
for (const r of RESOURCES) for (const f of r.fields) if (f.type === 'ref') (back[f.ref!] ??= []).push(`${r.key}_${f.name} ${r.key}[] @relation("rel_${r.key}_${f.name}")`);

for (const r of RESOURCES) {
  const body: string[] = ['id String @id @default(uuid())'];
  if (!r.global) body.push('companyId String');
  for (const f of r.fields) body.push(...scalar(r, f));
  const has = (n: string) => r.fields.some((f) => f.name === n);
  if (r.req && !has('requestId')) body.push('requestId String?');
  body.push('createdAt DateTime @default(now())', 'updatedAt DateTime @updatedAt', 'createdById String?');
  if (!has('version')) body.push('version Int @default(1)');
  for (const b of back[r.key] ?? []) body.push(b);
  const idx = new Set<string>();
  if (!r.global) idx.add('companyId');
  for (const f of r.fields) if (f.type === 'ref') idx.add(f.name);
  if (r.req) idx.add('requestId');
  if (r.statusField) idx.add(r.statusField);
  for (const i of idx) body.push(`@@index([${i}])`);
  if (r.numField && !r.global) body.push(`@@unique([companyId, ${r.numField}])`);
  for (const u of r.unique ?? []) body.push(`@@unique([${u.join(', ')}])`);
  body.push(`@@map("${snake(r.key)}")`);
  lines.push(`model ${r.key} {\n${body.map((l) => '  ' + l).join('\n')}\n}\n`);
}

writeFileSync(new URL('../prisma/schema.prisma', import.meta.url), lines.join('\n'));
console.log(`Generated schema for ${RESOURCES.length} resources`);
